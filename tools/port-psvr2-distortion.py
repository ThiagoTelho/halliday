#!/usr/bin/env python3
"""Port Monado's PS VR2 lens distortion data into Halliday.

1. Converts the 1024-entry chromatic lookup table in Monado's psvr2_distortion.c into
   core/halliday-core/src/psvr2/distortion_lut.rs.
2. Compiles Monado's own psvr2_compute_distortion_asymmetric (with a stub header) and writes
   reference outputs to core/halliday-core/tests/fixtures/psvr2_distortion_reference.txt, which the
   Rust port is tested against.

Needs reference/monado (tools/fetch-reference.sh) and clang. Re-run only when Monado's file changes.
"""

import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "reference/monado/src/xrt/drivers/psvr2/psvr2_distortion.c"
LUT_OUT = ROOT / "core/halliday-core/src/psvr2/distortion_lut.rs"
FIXTURE_OUT = ROOT / "core/halliday-core/tests/fixtures/psvr2_distortion_reference.txt"

STUB_HEADER = """
#pragma once
struct xrt_vec2 { float x, y; };
struct xrt_uv_triplet { struct xrt_vec2 r, g, b; };
"""

HARNESS = r"""
#include <stdio.h>
#include "xrt/xrt_defines.h"
void psvr2_compute_distortion_asymmetric(float *calibration, struct xrt_uv_triplet *out, int eye, float u, float v);

int main(void) {
    /* Two calibrations: Halliday's fallback (Monado's offsets with an identity rotation; Monado's
     * own fallback leaves cos/sin at zero, which collapses the image) and a realistic one. */
    float cals[2][8] = {
        {-0.09919293f, 0.0f, 0.09919293f, 0.0f, 1.0f, 0.0f, 1.0f, 0.0f},
        {-0.0987f, 0.0006f, 0.0994f, -0.0003f, 0.99998f, -0.0061f, 0.99999f, 0.0043f},
    };
    for (int c = 0; c < 2; c++)
        for (int eye = 0; eye < 2; eye++)
            for (int iv = 0; iv <= 16; iv++)
                for (int iu = 0; iu <= 16; iu++) {
                    float u = iu / 16.0f, v = iv / 16.0f;
                    struct xrt_uv_triplet t;
                    psvr2_compute_distortion_asymmetric(cals[c], &t, eye, u, v);
                    printf("%d %d %.9g %.9g %.9g %.9g %.9g %.9g %.9g %.9g\n", c, eye, u, v,
                           t.r.x, t.r.y, t.g.x, t.g.y, t.b.x, t.b.y);
                }
    return 0;
}
"""


def port_lut(text: str) -> None:
    body = text[text.index("lookup[] = {") :]
    triples = re.findall(r"\{\s*([-\d.e]+),\s*([-\d.e]+),\s*([-\d.e]+)\s*\}", body)
    if len(triples) != 1024:
        sys.exit(f"expected 1024 lookup entries, found {len(triples)}")
    rows = "\n".join(f"    [{r}, {g}, {b}]," for r, g, b in triples)
    LUT_OUT.write_text(
        "// Generated by tools/port-psvr2-distortion.py from Monado's\n"
        "// src/xrt/drivers/psvr2/psvr2_distortion.c (BSL-1.0; Joel Valenciano, Beyley Cardellio).\n"
        "// See THIRD-PARTY.md. Do not edit by hand.\n\n"
        "/// Chromatic scale per channel (r, g, b), indexed by squared radius × 1023.\n"
        "#[rustfmt::skip]\n"
        "#[allow(clippy::excessive_precision)]\n"
        f"pub(super) static LUT: [[f32; 3]; 1024] = [\n{rows}\n];\n"
    )


def write_fixture() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        tmp = pathlib.Path(tmp)
        (tmp / "xrt").mkdir()
        (tmp / "xrt/xrt_defines.h").write_text(STUB_HEADER)
        (tmp / "harness.c").write_text(HARNESS)
        exe = tmp / "harness"
        subprocess.run(
            ["clang", "-O0", "-ffp-contract=off", "-I", str(tmp), str(SRC), str(tmp / "harness.c"), "-o", str(exe)],
            check=True,
        )
        out = subprocess.run([str(exe)], check=True, capture_output=True, text=True).stdout
    FIXTURE_OUT.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE_OUT.write_text(
        "# Reference outputs of Monado's psvr2_compute_distortion_asymmetric, generated by\n"
        "# tools/port-psvr2-distortion.py. Columns: calibration eye u v r.x r.y g.x g.y b.x b.y\n" + out
    )


def main() -> None:
    port_lut(SRC.read_text())
    write_fixture()
    print(f"wrote {LUT_OUT.relative_to(ROOT)} and {FIXTURE_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
